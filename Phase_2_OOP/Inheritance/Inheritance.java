package Inheritance;
public class Inheritance {

    public static void main(String[] args) {

        System.out.println("Learning Topic: Inheritance");
        // inheritance is a mechanism in Java by which one class is allowed to inherit the features (fields and methods) of another class.
        // The class that inherits is called the subclass (or child class), and the class being inherited from is called the superclass (or parent class).
        // Inheritance provides the following benefits:
        // 1. Code Reusability: Inheritance supports the concept of "reusing" code. You can create a new class that inherits the properties and methods of an existing class, which reduces code duplication and promotes code reuse.
        // 2. Method Overriding: Inheritance allows a subclass to provide a specific implementation of a method that is already defined in its superclass
        // Access Modifiers in Inheritance:
        // 1. Public: A public member of a superclass can be accessed by any subclass, regardless of whether it is in the same package or not.
        // 2. Protected: A protected member of a superclass can be accessed by subclasses in the same package or subclasses in different packages.
        // 3. Default (Package-Private): A default member of a superclass can only be accessed by subclasses in the same package.
        // types of inheritance in java:
        // 1. Single Inheritance: A subclass inherits from a single superclass.
        // 2. Multilevel Inheritance: A subclass inherits from a superclass, and then another subclass inherits from that subclass, forming a chain of inheritance.
        // 3. Hierarchical Inheritance: Multiple subclasses inherit from a single superclass.
        // 4. Multiple Inheritance (through interfaces): A class can implement multiple interfaces, allowing it to inherit behavior from multiple sources.  
        
    }
}
