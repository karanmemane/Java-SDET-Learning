        System.out.println("In Java, a method is a block of code that performs a specific task. Methods are used to organize code into reusable sections and can take parameters and return values. Here's an example of a simple method in Java:");
        System.out.println("public static void greet(String name) {");
        System.out.println("    System.out.println(\"Hello, \" + name + \"!\");");
        System.out.println("}");
        System.out.println("In this example, we define a method called greet that takes a String parameter called name. The method prints a greeting message to the console using the provided name. To call this method, you can use the following code in the main method:");
