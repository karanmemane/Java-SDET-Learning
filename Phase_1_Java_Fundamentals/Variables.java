public class Variables {

    public static void main(String[] args) {

        System.out.println("Learning Topic: Variables");
        System.out.println("In Java, a variable is a container that holds data that can be changed during the execution of a program. Variables have a specific data type that determines the kind of data they can hold. Here are some examples of variable declarations in Java:");
        System.out.println("int myInt = 100; // Integer variable");
        System.out.println("double myDouble = 3.14; // Double variable");
        System.out.println("char myChar = 'A'; // Character variable");
        System.out.println("boolean myBoolean = true; // Boolean variable");
        System.out.println("String myString = \"Hello, Java!\"; // String variable");
        System.out.println("In this example, we declare variables of different data types and assign values to them. The variable names (myInt, myDouble, myChar, myBoolean, myString) are used to reference the values stored in the variables. You can use these variables in your Java programs to store and manipulate data. Now you can try declaring and using variables in your own Java programs!");    
        

    }
}
